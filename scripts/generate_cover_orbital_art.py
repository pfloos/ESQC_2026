#!/usr/bin/env python3
"""Print editable TikZ contours for the proposed orbital-atlas cover.

Regeneration requires numpy and contourpy; compiling the saved vector artwork
requires only the chapter's existing TikZ packages. This is an illustrative
linear combination of six Gaussian functions, not a computed molecular orbital.
"""

import math

import contourpy
import numpy as np


def simplify(points, tolerance=0.006):
    """Reduce a polyline without moving it by more than the display tolerance."""
    if len(points) <= 2:
        return points
    delta = points[-1] - points[0]
    length = np.linalg.norm(delta)
    if length < 1e-12:
        half = len(points) // 2
        return np.concatenate((simplify(points[: half + 1])[:-1],
                               simplify(points[half:])))
    offset = points - points[0]
    distance = np.abs(delta[0] * offset[:, 1] - delta[1] * offset[:, 0]) / length
    index = int(np.argmax(distance))
    if distance[index] <= tolerance:
        return points[[0, -1]]
    return np.concatenate((simplify(points[: index + 1])[:-1],
                           simplify(points[index:])))


def path(points, style, command="path"):
    if np.linalg.norm(points[0] - points[-1]) > 1e-5:
        raise ValueError("A contour reaches the sampling boundary")
    points = simplify(points)
    coordinates = " -- ".join(f"({x:.4f},{y:.4f})" for x, y in points[:-1])
    print(f"\\{command}[{style}] {coordinates} -- cycle;")


def main():
    axis = np.linspace(-4.5, 4.5, 361)
    x, y = np.meshgrid(axis, axis)
    centers = [(1.45 * math.cos(k * math.pi / 3),
                1.45 * math.sin(k * math.pi / 3)) for k in range(6)]
    orbital = np.zeros_like(x)
    envelope = np.zeros_like(x)
    for k, (cx, cy) in enumerate(centers):
        distance = (x - cx) ** 2 + (y - cy) ** 2
        orbital += (-1) ** k * np.exp(-1.4 * distance)
        envelope += np.exp(-0.58 * distance)
    print("% Generated by scripts/generate_cover_orbital_art.py; native vector artwork.")
    print("% Phase contours of an illustrative six-center Gaussian combination.")
    print("% Not an ab-initio orbital, density, or identified molecular species.")
    print("\\begin{scope}[line join=round,line cap=round,rotate=15]")
    contours = contourpy.contour_generator(x=axis, y=axis, z=envelope)
    for level in (0.06, 0.10, 0.17, 0.28, 0.44, 0.66, 0.92, 1.20, 1.48, 1.70):
        for points in contours.lines(level):
            path(points, "hfBlue!24,line width=0.32pt", "draw")
    for sign, color in ((1, "hfTeal"), (-1, "hfOrange")):
        contours = contourpy.contour_generator(x=axis, y=axis, z=sign * orbital)
        for index, level in enumerate(np.linspace(0.045, 0.84, 13)):
            tint = 12 + 5 * index
            for points in contours.lines(float(level)):
                path(points, f"fill={color}!{tint},draw={color}!65,line width=0.23pt")
    for cx, cy in centers:
        print(f"\\filldraw[fill=white,draw=hfGreenDark,line width=0.5pt] "
              f"({cx:.4f},{cy:.4f}) circle (0.040);")
    print("\\end{scope}")


if __name__ == "__main__":
    main()
